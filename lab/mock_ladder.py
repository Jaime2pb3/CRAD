#!/usr/bin/env python3
"""Rung 3 of the GPU ladder, in one command: the whole lab on the CPU mock model.

Usage:  CRAD_MOCK_MODEL=1 python mock_ladder.py        (~1-3 min on CPU, zero GPU)

Works in a throw-away copy of the lab (never touches captures/ here) and checks the
wiring that the real GPU session depends on:

  1  preflight_gpu.py            all blocking checks green on the mock
  2  capture.py                  verdict INCONSISTENT with EXACTLY one problem: the mock stamp
                                 (frame counts, calibration counts, value-level geometry,
                                 token ids all re-verified by capture.check_capture)
  3  crad_contract.py check      shared ruler agrees, decisions match result.jsonl
  4  dose_probe.py               dose 0 reproduces the captured turn in a NEW process
  5  patch_probe.py  (planted)   baseline reproduces + self-patch gate at every layer
  6  patch_batch.py  (planted)   gates + every mode + summary written

Steps 5-6 plant TRUTH/SELF_FICTION decisions (the mock never writes "access code is").
The planting code is generated inside the temp copy only; it does not exist in the lab.
Numbers produced here mean nothing; only exit codes and gates do.
"""
from __future__ import annotations

import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

LAB = Path(__file__).resolve().parent
SKIP = ("captures", "runs", "preflight", "analysis", "__pycache__", ".ipynb_checkpoints")
PLANTED = '''"""TEST-ONLY, generated by mock_ladder.py inside a temp copy. Plants decisions on the mock."""
import runpy, sys
from pathlib import Path
LAB = Path(__file__).resolve().parent; sys.path.insert(0, str(LAB)); sys.path.insert(0, str(LAB / "src"))
import launch_common as lc, crad_base, crad_contract as cc
lc.install_model_probe(crad_base)
def decision(self, draw, target_turn=cc.DEFAULT_TARGET_TURN, anchor=cc.DEFAULT_ANCHOR):
    toks, _ = cc.turns_from_capture(self.z, draw)
    if target_turn not in toks or len(toks[target_turn]) < 8:
        return cc.Decision("NO_TARGET", target_turn)
    out = "TRUTH" if draw % 2 == 0 else "SELF_FICTION"
    return cc.Decision(out, target_turn, row=5, commit_row=6, commit_token=toks[target_turn][6],
                       token=toks[target_turn][5], content="BLUEFALCON" if out == "TRUTH" else f"FIC{draw}")
cc.SharedCalibration.decision = decision
script = str(LAB / sys.argv[1]); sys.argv = [script] + sys.argv[2:]
runpy.run_path(script, run_name="__main__")
'''


def main() -> int:
    if os.environ.get("CRAD_MOCK_MODEL") != "1":
        raise SystemExit("mock_ladder.py: run with CRAD_MOCK_MODEL=1")
    tmp = Path(tempfile.mkdtemp(prefix="crad_mock_"))
    work = tmp / "lab"
    shutil.copytree(LAB, work, ignore=shutil.ignore_patterns(*SKIP, "*.ipynb", "*.zip"))
    (work / "_planted.py").write_text(PLANTED)
    cfg = json.loads((work / "configs" / "qwen2.5-7b_T0.7_cal0_L14-20_s42.json").read_text())
    cfg["name"] = "MOCK_wiring"
    cfg["args"].update({"n-tokens": 24, "draws": 6, "n-perm": 20})
    (work / "configs" / "mock.json").write_text(json.dumps(cfg, indent=2))
    py = sys.executable
    results = []

    def step(name, cmd, want_rc=0):
        print(f"\n[mock-ladder] {name}\n$ {' '.join(cmd)}", flush=True)
        p = subprocess.run(cmd, cwd=work, capture_output=True, text=True)
        ok = p.returncode == want_rc
        tail = "\n".join((p.stdout + p.stderr).strip().splitlines()[-6:])
        print(tail)
        results.append((name, ok))
        if not ok:
            print(f"[mock-ladder] RED at '{name}' (exit {p.returncode}, wanted {want_rc}). Full output:\n"
                  + p.stdout[-4000:] + p.stderr[-4000:])
        return ok

    if not step("1 preflight_gpu on mock", [py, "preflight_gpu.py", "configs/mock.json"]):
        return 1
    if not step("2 capture (INCONSISTENT expected: mock stamp)",
                [py, "capture.py", "configs/mock.json", "--superset", "13", "28"], want_rc=1):
        return 1
    cap = sorted((work / "captures").glob("*_MOCK_wiring_cap13-28"))[-1]
    cj = json.loads((cap / "capture.json").read_text())
    only_stamp = cj["problems"] == ["MOCK model: wiring test only, never data"]
    print(f"[mock-ladder] capture problems: {cj['problems']}")
    results.append(("2b capture: the ONLY problem is the mock stamp", only_stamp))
    if not only_stamp:
        return 1
    cj["problems"] = []
    (cap / "capture.json").write_text(json.dumps(cj, indent=2))   # temp copy only
    rel = str(cap.relative_to(work))
    ok = (step("3 crad_contract check", [py, "crad_contract.py", "check", rel])
          and step("4 dose_probe (dose 0 must reproduce the capture)",
                   [py, "mock_run.py", "dose_probe.py", rel, "--turn", "3", "--direction", "R", "--doses", "0", "0.05"])
          and step("5 patch_probe (planted decisions)",
                   [py, "_planted.py", "patch_probe.py", rel, "--source", "0", "--target", "1", "--layers", "14", "19", "26"])
          and step("6 patch_batch (planted decisions)",
                   [py, "_planted.py", "patch_batch.py", rel, "--layers", "14", "26", "--n-perm", "200"]))
    print("\n[mock-ladder] summary")
    for name, good in results:
        print(f"  [{'ok' if good else 'FAIL'}] {name}")
    shutil.rmtree(tmp, ignore_errors=True)
    if ok and all(g for _, g in results):
        print("[mock-ladder] GREEN: wiring verified end to end on CPU. Numbers above are meaningless by design.")
        return 0
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
